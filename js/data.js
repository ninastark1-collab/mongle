function lifespanYears(s) {
  const nums = (String(s).match(/\d+/g) || []).map(Number);
  if (!nums.length) return 1;
  const avg = nums.length > 1 ? (nums[0] + nums[1]) / 2 : nums[0];
  return /개월/.test(s) ? avg / 12 : avg;
}

